//! Instruction counts for compressing insert frames (gungraun).
//!
//! Each case compresses the eight frames of `support/frames.rs` under one of
//! the codecs the sink's `compression` key selects, in two implementations:
//!
//! - `upstream_lz4`, `upstream_zstd1` and `upstream_zstd3` use the
//!   `clickhouse` client's own codec, `CompressedData::new`, which is the work
//!   `InsertFormatted::send` does for every frame when client compression is
//!   on;
//! - `spate_lz4`, `spate_zstd1` and `spate_zstd3` use the sink's frame codec
//!   through `testing::frame_codec`, plus the copy of each block into an
//!   exact-size `Bytes` that the terminal stage makes. The codec is made and
//!   has coded one frame before collection starts, as on a pipeline thread
//!   that has sealed chunks before.
//!
//! The frames are Native blocks of the `events` corpus sealed at
//! `ChunkConfig`'s default chunk target, so each is the size production
//! seals. A count here covers all eight frames; divide by eight for a
//! per-frame figure.
//!
//! Needs valgrind and a same-version `gungraun-runner`: run it with
//! `cargo xtask bench counted`.

// `library_benchmark` and `library_benchmark_group` expand to public modules,
// functions and constants of their own, none of which carry documentation.
#![expect(missing_docs, reason = "items are generated by gungraun macros")]

use bytes::Bytes;
use clickhouse::Compression;
use clickhouse::insert_formatted::CompressedData;
use gungraun::{Dhat, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main};
use spate_core::sink::FrameCodec;
use std::hint::black_box;

#[allow(dead_code, reason = "this target compresses the events corpus only")]
#[path = "support/rows.rs"]
mod rows;

#[path = "support/frames.rs"]
mod frames;

use frames::{FRAMES, Frame};

/// The frames and the codec one case compresses them with.
struct Rig {
    frames: Vec<Frame>,
    compression: Compression,
}

fn rig(compression: Compression) -> Rig {
    Rig {
        frames: frames::native_frames(FRAMES),
        compression,
    }
}

/// The measured work: every frame through the client's codec.
///
/// `#[inline(never)]` keeps the loop a named callee inside the collected
/// region, so the optimizer cannot move it past the callgrind toggle the
/// benchmark function is wrapped in. The outputs are returned so freeing them
/// happens after collection stops.
#[inline(never)]
fn compress_frames(rig: &Rig) -> Vec<CompressedData> {
    rig.frames
        .iter()
        .map(|f| CompressedData::new(black_box(&f.bytes), rig.compression).expect("compresses"))
        .collect()
}

// A `///` comment is a `#[doc]` attribute, which `#[library_benchmark]`
// rejects. The rig is returned with the outputs so its frames are freed after
// collection stops as well.
#[library_benchmark]
#[bench::upstream_lz4(rig(Compression::Lz4))]
#[bench::upstream_zstd1(rig(Compression::Zstd(1)))]
#[bench::upstream_zstd3(rig(Compression::Zstd(3)))]
fn compress_upstream(rig: Rig) -> (Rig, Vec<CompressedData>) {
    let out = compress_frames(&rig);
    (rig, out)
}

/// The frames and the sink's codec for one `compression` value.
struct SpateRig {
    frames: Vec<Frame>,
    codec: Box<dyn FrameCodec>,
}

fn spate_rig(compression: &str) -> SpateRig {
    let frames = frames::native_frames(FRAMES);
    let compression = compression.parse().expect("a compression value");
    let mut codec = spate_clickhouse::testing::frame_codec(compression)
        .expect("a compressing codec")
        .make();
    codec.encode_frame(&frames[0].bytes).expect("warms");
    SpateRig { frames, codec }
}

/// The measured work: every frame through the sink's codec, copied out as
/// the terminal stage copies it. `#[inline(never)]` as for `compress_frames`.
#[inline(never)]
fn code_frames(rig: &mut SpateRig) -> Vec<Bytes> {
    rig.frames
        .iter()
        .map(|f| {
            let block = rig.codec.encode_frame(black_box(&f.bytes)).expect("codes");
            Bytes::copy_from_slice(block)
        })
        .collect()
}

#[library_benchmark]
#[bench::spate_lz4(spate_rig("lz4"))]
#[bench::spate_zstd1(spate_rig("zstd:1"))]
#[bench::spate_zstd3(spate_rig("zstd:3"))]
fn compress_spate(mut rig: SpateRig) -> (SpateRig, Vec<Bytes>) {
    let out = code_frames(&mut rig);
    (rig, out)
}

library_benchmark_group!(
    name = frame;
    benchmarks = compress_upstream, compress_spate
);

// DHAT as an extra tool, as the encode bench does: the callgrind invocation,
// and so every `Ir` baseline, is the same with and without it.
main!(
    config = LibraryBenchmarkConfig::default().tool(Dhat::with_args(["--num-callers=500"])),
    library_benchmark_groups = frame
);
