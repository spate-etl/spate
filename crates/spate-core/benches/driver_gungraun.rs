//! Instruction counts for a pipeline thread's poll loop (gungraun).
//!
//! One shape: [`poll_loop`](spate_core::bench_seams::poll_loop) runs the
//! thread's real loop for 10,000 iterations over scripted lanes, the queues of
//! a sink, and a chain that only drains. Every iteration heartbeats, drains the
//! control channel, scans the shard queues for the backpressure controller,
//! picks the next lane, checks its pending-batch gate and polls it.
//!
//! - `empty_one_lane`: one lane, one shard, every poll empty. The floor.
//! - `empty_64_lanes`: work that scales with the lanes a thread owns.
//! - `empty_256_shards`: work that scales with the sink's shard queues.
//! - `batches_64_lanes`: every poll a batch of 16 payloads, adding the path
//!   that pushes a batch through the chain and counts it.
//!
//! The thread is built in the `#[bench]` argument, outside the collected
//! region. The loop handles the lane assignments and the stop itself, so both
//! are counted once per case. Every case runs with the controller unpaused and
//! no push blocked: the paused and blocked paths sleep between iterations and
//! hold a pause on the real clock, so no count of them would be stable.
//!
//! The loop reads the system clock twice per poll, for its poll-duration
//! histogram. That read is in the code under measurement, so every case
//! counts it.
//!
//! The two 64-lane cases move between runs, by up to 0.05% so far. Each lane's
//! pending-batch gate sits in a map whose hasher draws a fresh seed each time
//! it is built, so the 64 partitions hash into a different number of probes on
//! each run. With that map on a fixed hasher, every case repeated to the
//! instruction over three runs. The one-lane cases repeat as they are.
//!
//! Needs valgrind and a same-version `gungraun-runner`: run it with
//! `cargo xtask bench counted`.

// `library_benchmark` and `library_benchmark_group` expand to public modules,
// functions and constants of their own, none of which carry documentation.
#![expect(missing_docs, reason = "items are generated by gungraun macros")]

use gungraun::{Dhat, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main};
use spate_core::bench_seams::PollLoop;
use std::any::Any;

#[path = "support/driver_rig.rs"]
mod driver_rig;

use driver_rig::{BATCHES_64_LANES, Case, EMPTY_64_LANES, EMPTY_256_SHARDS, EMPTY_ONE_LANE};

/// The run, in a named frame: a callgrind toggle on the benchmark function's
/// module bounds collection, and work inlined there can fall outside it.
#[inline(never)]
fn drive(run: PollLoop) -> ((u64, u64, u64, u64), Box<dyn Any + Send>) {
    run()
}

// The kept state is returned so it is freed outside the collected region.
#[library_benchmark]
#[bench::empty_one_lane(EMPTY_ONE_LANE, EMPTY_ONE_LANE.build())]
#[bench::empty_64_lanes(EMPTY_64_LANES, EMPTY_64_LANES.build())]
#[bench::empty_256_shards(EMPTY_256_SHARDS, EMPTY_256_SHARDS.build())]
#[bench::batches_64_lanes(BATCHES_64_LANES, BATCHES_64_LANES.build())]
fn poll_loop(case: Case, run: PollLoop) -> Box<dyn Any + Send> {
    let (counts, state) = drive(run);
    assert_eq!(counts, case.expected(), "{}: counts moved", case.name);
    state
}

library_benchmark_group!(
    name = driver_group;
    benchmarks = poll_loop
);

// DHAT as an extra tool, with the deepest stacks it allows, as in
// `backpressure_gungraun.rs`.
main!(
    config = LibraryBenchmarkConfig::default().tool(Dhat::with_args(["--num-callers=500"])),
    library_benchmark_groups = driver_group
);
