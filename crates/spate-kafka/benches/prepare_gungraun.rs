//! Instruction counts for the sink writer's batch preparation (gungraun).
//!
//! One shape: a sealed batch through
//! [`prepare_batch`](spate_kafka::bench_seams::prepare_batch), which runs the
//! writer's work on a shard worker short of the send. It parses every frame
//! back into messages and checks the count against the batch's rows, as the
//! writer does before its first send, and builds each message's librdkafka
//! header list, as the writer does just before sending that message.
//!
//! The send, the delivery reports and the wait for them are out of reach: they
//! need a broker, and they run inside the async `write_batch`.
//!
//! The cases are the encode benches' message shapes, framed by the same
//! encoder:
//!
//! - `keyless` — payload only. The floor every message pays: one parse and one
//!   slot in the batch's message list.
//! - `keyed` — adds a key. The delta against `keyless` is one more section to
//!   read.
//! - `stamped_headers` — keyless with four headers per message. Headers are the
//!   one part whose preparation scales with a count: each is parsed, checked as
//!   UTF-8 and copied into a header list librdkafka allocates.
//!
//! Needs valgrind and a same-version `gungraun-runner`: run it with
//! `cargo xtask bench counted`.

// `library_benchmark` and `library_benchmark_group` expand to public modules,
// functions and constants of their own, none of which carry documentation.
#![expect(missing_docs, reason = "items are generated by gungraun macros")]

use gungraun::{Dhat, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main};

#[expect(dead_code, reason = "only the rigs that frame a batch are used here")]
#[path = "support/encode_rig.rs"]
mod encode_rig;
#[path = "support/messages.rs"]
mod messages;
#[path = "support/prepare_rig.rs"]
mod prepare_rig;

use prepare_rig::{Batch, keyed, keyless, prepare_run, stamped};

// The batch is returned so its frame is dropped outside the collected region.
#[library_benchmark]
#[bench::keyless(keyless())]
#[bench::keyed(keyed())]
#[bench::stamped_headers(stamped())]
fn prepare(batch: Batch) -> Batch {
    assert_eq!(prepare_run(&batch), batch.expected, "counts moved");
    batch
}

library_benchmark_group!(
    name = prepare_group;
    benchmarks = prepare
);

// DHAT as an extra tool, with the deepest stacks it allows, as in
// `encode_gungraun.rs`. It also sees the header lists librdkafka allocates
// through `malloc`, which the allocation snapshot cannot.
main!(
    config = LibraryBenchmarkConfig::default().tool(Dhat::with_args(["--num-callers=500"])),
    library_benchmark_groups = prepare_group
);
