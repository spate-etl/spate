//! Instruction counts for the reader's descriptor decode (gungraun).
//!
//! A reader decodes a unit's descriptor when it receives the unit. The parse
//! allocates a `String` for every key and every ETag where the serializer only
//! borrowed them, and `decode` runs the parser **twice over the same bytes**,
//! probing the version before parsing the document, so an incompatible
//! descriptor is reported as a version mismatch rather than as a parse error.
//!
//! One shape: 6,400 descriptors of one member each, which is what a listing of
//! objects read whole produces. A byte-range unit is this shape plus a `range`
//! field.
//!
//! Descriptors are encoded in the fixture, never in the measured region, so
//! this counts parsing only.
//!
//! Needs valgrind and a same-version `gungraun-runner`, neither of which
//! exists on every developer machine: run it with `cargo xtask bench counted`.

// `library_benchmark` and `library_benchmark_group` expand to public modules,
// functions and constants of their own, none of which carry documentation, so
// the workspace's `missing_docs` lint has nothing to bite on here.
#![expect(missing_docs, reason = "items are generated by gungraun macros")]

use gungraun::{Dhat, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main};
use spate_s3::SplitDescriptor;
use std::hint::black_box;

#[path = "support/descriptors.rs"]
mod descriptors;

// The corpus is encoded in the `#[bench]` argument expression, which gungraun
// evaluates outside the collected region, and moved in. Both the encoded
// bytes and the decoded descriptors are handed back rather than dropped in
// place: freeing several thousand documents and the strings parsed out of
// them inside the region would charge the count for teardown. A `///`
// comment is a `#[doc]` attribute, which `#[library_benchmark]` rejects.
//
/// The measured work: every descriptor of the corpus parsed in one pass.
///
/// It lives outside the benchmark function and is `#[inline(never)]`.
/// Collection is bounded by a callgrind toggle on the module the benchmark
/// macro wraps the function in, and a toggle *flips* collection rather than
/// forcing it on, so work the optimizer leaves in an unstable shape inside
/// that module can end up outside the collected region entirely. Two earlier
/// revisions of this bench showed it: one built the vector with
/// `.iter().map().collect()` and counted 3,249 Ir, the other used a plain
/// `for` in the benchmark function and counted 858,925 Ir whose callgrind
/// profile was **100% glibc `malloc_consolidate` and `unlink_chunk`**, with
/// no `serde_json` frame at all and the same total whether the corpus held
/// 400 documents or 6,400.
///
/// A named, never-inlined callee is a frame the toggle cannot lose, which the
/// two working benches in this crate get by calling into `bench_seams`. This
/// one reaches its work through public API instead, so the callee lives here.
#[inline(never)]
fn decode_plan(encoded: &[Vec<u8>]) -> Vec<SplitDescriptor> {
    let mut decoded = Vec::with_capacity(encoded.len());
    for bytes in encoded {
        decoded.push(SplitDescriptor::decode(bytes).expect("the fixture decodes"));
    }
    decoded
}

#[library_benchmark]
#[bench::single_member_splits(descriptors::single_member_plan())]
fn decode(encoded: Vec<Vec<u8>>) -> (Vec<Vec<u8>>, Vec<SplitDescriptor>) {
    let decoded = decode_plan(black_box(&encoded));
    // Asserted rather than returned unchecked, so a fixture that silently
    // stopped carrying members could not pass as a fast one. Walked with a
    // `for` rather than an iterator chain: a closure here is exactly the
    // shape that went missing from the collected region above.
    let mut members = 0;
    for descriptor in &decoded {
        assert_eq!(
            descriptor.objects.len(),
            1,
            "a descriptor carries one member"
        );
        members += descriptor.objects.len();
    }
    assert_eq!(
        members,
        descriptors::MEMBERS,
        "the corpus decoded to a different member count"
    );
    (encoded, decoded)
}

library_benchmark_group!(name = descriptor; benchmarks = decode);

// DHAT is scoped as an extra tool rather than a callgrind argument: the
// callgrind invocation, and so every `Ir` baseline, is bit-identical with
// and without it. `--num-callers=500` (the maximum) keeps allocation stacks
// deep enough to attribute to the parse under measurement rather than to
// whichever frame valgrind's default depth would otherwise cut at.
main!(
    config = LibraryBenchmarkConfig::default().tool(Dhat::with_args(["--num-callers=500"])),
    library_benchmark_groups = descriptor
);
