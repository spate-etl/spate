//! Instruction counts for chunk-fed record framing (gungraun).
//!
//! One shape, driving a run of objects through one framer as a lane does over
//! the members of its split, parameterized by codec and by how the object is
//! entered:
//!
//! - `plain_whole` — one 4 MiB NDJSON object in fetch-sized chunks. The
//!   per-byte cost of the whole lane, and the denominator here.
//! - `gzip_whole`, `zstd_whole` — the same body stored compressed. These are
//!   the **negative control** for byte-range subdivision: a whole-stream
//!   codec cannot be entered at an arbitrary offset, so subdivision must
//!   never apply to them. If either count moves with a change to
//!   subdivision, the capability probe has leaked into the whole-stream path.
//! - `gzip_multi_member`, `zstd_multi_frame` — the same body again, stored as
//!   sixteen independently-encoded streams concatenated into one object,
//!   which is what an export key appended to by a run of upload sessions
//!   holds. Decoded content is byte-identical to the `_whole` pair, so the
//!   difference between them is the per-stream term those fixtures never
//!   charge (trailer validation, decoder reinitialization, the next stream's
//!   header parse) **plus** whatever the compressed input's own shape
//!   contributes, since sixteen streams each starting from a cleared window
//!   do not compress to the same bytes as one. The pair bounds that term
//!   rather than isolating it. Both codecs have to read every stream; a
//!   decoder that stopped at the first would drop fifteen sixteenths of the
//!   object, and the asserted record count turns that into a failure rather
//!   than into a welcome fall in the number.
//! - `plain_mid_offset` — the same object fed from a byte offset that falls
//!   *inside* a record. The framer frames the bytes it is given, so it emits
//!   the partial leading line as a record, and the case asserts that count.
//! - `plain_range` — the same entry read as a byte-range split through
//!   `frame_range`. A range owns only the records that start inside it, so
//!   the trim drops the partial leading line and the case asserts one record
//!   fewer than `plain_mid_offset`. The difference between the two is the
//!   trim plus the window copy that stands in for the GET.
//! - `plain_many_small` — sixteen small objects through one framer: the
//!   per-object codec resolution and state reset of a framer reused across
//!   objects.
//!
//! Bodies are compressed in the fixture, never in the measured region, so
//! these count decompression only. Framing is done with `spate-json`'s
//! `NdjsonFramer` rather than a local copy: this crate ships no framer of its
//! own, and object storage carrying newline-delimited JSON is the pairing
//! production runs.
//!
//! Needs valgrind and a same-version `gungraun-runner`, neither of which
//! exists on every developer machine: run it with `cargo xtask bench counted`.

// `library_benchmark` and `library_benchmark_group` expand to public modules,
// functions and constants of their own, none of which carry documentation, so
// the workspace's `missing_docs` lint has nothing to bite on here.
#![expect(missing_docs, reason = "items are generated by gungraun macros")]

use gungraun::{Dhat, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main};
use spate_s3::bench_seams::{frame_objects, frame_range};
use std::hint::black_box;

#[path = "support/framing_rig.rs"]
mod framing_rig;
#[path = "support/ndjson.rs"]
mod ndjson;

use framing_rig::{
    RangeRig, Rig, gzip_multi_member, gzip_whole, make_framer, plain_many_small, plain_mid_offset,
    plain_range, plain_whole, zstd_multi_frame, zstd_whole,
};

// Each case returns its rig rather than dropping it: a value moved into the
// benchmark function is dropped inside the collected region, and freeing a
// few megabytes of chunk buffers would swamp the framing it is meant to
// measure. A `///` comment is a `#[doc]` attribute, which
// `#[library_benchmark]` rejects.
#[library_benchmark]
#[bench::plain_whole(plain_whole())]
#[bench::gzip_whole(gzip_whole())]
#[bench::zstd_whole(zstd_whole())]
#[bench::gzip_multi_member(gzip_multi_member())]
#[bench::zstd_multi_frame(zstd_multi_frame())]
#[bench::plain_mid_offset(plain_mid_offset())]
#[bench::plain_many_small(plain_many_small())]
fn frame(rig: Rig) -> Rig {
    let records = frame_objects(rig.compression, make_framer(), black_box(&rig.objects))
        .expect("the fixture frames cleanly");
    assert_eq!(
        records, rig.expect_records,
        "framed record count changed; if that is intended, the fixture's \
         expectation is the contract being edited"
    );
    rig
}

#[library_benchmark]
#[bench::plain_range(plain_range())]
fn frame_one_range(rig: RangeRig) -> RangeRig {
    let records = frame_range(
        make_framer(),
        black_box(&rig.body),
        rig.start,
        rig.body.len() as u64,
        b'\n',
        ndjson::RANGE_BYTES,
        ndjson::CHUNK_BYTES,
    )
    .expect("the fixture frames cleanly");
    assert_eq!(
        records, rig.expect_records,
        "a range framed a different record count; if that is intended, the \
         fixture's expectation is the contract being edited"
    );
    rig
}

library_benchmark_group!(name = framing; benchmarks = frame, frame_one_range);

// DHAT is scoped as an extra tool rather than a callgrind argument: the
// callgrind invocation, and so every `Ir` baseline, is bit-identical with
// and without it. `--num-callers=500` (the maximum) keeps allocation stacks
// deep enough to attribute to the framing under measurement rather than to
// whichever frame the default depth of 4 happens to cut at.
main!(
    config = LibraryBenchmarkConfig::default().tool(Dhat::with_args(["--num-callers=500"])),
    library_benchmark_groups = framing
);
